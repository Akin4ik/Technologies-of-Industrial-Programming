//задание 1
#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");
    
    int N, M;
    cout << "Введите размеры лабиринта (N и M): ";
    cin >> N >> M;
    
    char lab[100][100]; // сам лабиринт
    int max_pdf[100][100]; // здесь храним максимальное число pdf до каждой клетки
    
    int start_i = 0, start_j = 0; // координаты старта (где P.Diddy)
    int end_i = 0, end_j = 0;     // координаты выхода
    
    cout << "Введите лабиринт (0 - пусто, 1 - стена, P - pdf, E - выход):" << endl;
    for (int i = 0; i < N; i++) {
        for (int j = 0; j < M; j++) {
            cin >> lab[i][j];
            max_pdf[i][j] = -1; // -1 значит, что мы тут ещё не были
            
            // Ищем, откуда стартует Диди и где выход
            // Предполагаем, что старт - это какая-то пустая клетка (или его явно обозначают)
            // Если в условии не сказано, где старт, обычно это верхний левый угол (0,0)
            if (lab[i][j] == 'E') {
                end_i = i;
                end_j = j;
            }
        }
    }
    
    // Стартуем из левого верхнего угла (0, 0), как это обычно бывает в таких задачах,
    // если не сказано иное
    start_i = 0;
    start_j = 0;
    
    // Если на старте лежит файл - сразу его считаем
    if (lab[start_i][start_j] == 'P') {
        max_pdf[start_i][start_j] = 1;
    } else {
        max_pdf[start_i][start_j] = 0;
    }
    
    // Очередь для BFS. В обычных массивах
    // Так как лабиринт максимум 100x100, то максимум клеток 10000.
    // Для очереди заведем массивы на 10000 элементов.
    int q_i[10000]; 
    int q_j[10000];
    int head = 0; // откуда читаем
    int tail = 0; // куда пишем
    
    // Кладем стартовую клетку в очередь
    q_i[tail] = start_i;
    q_j[tail] = start_j;
    tail = tail + 1;
    
    // Направления: вверх, вниз, влево, вправо
    int di[4] = {-1, 1, 0, 0};
    int dj[4] = {0, 0, -1, 1};
    
    // Пока очередь не пуста
    while (head < tail) {
        int cur_i = q_i[head];
        int cur_j = q_j[head];
        head = head + 1;
        
        // Пробуем пойти в 4 стороны
        for (int d = 0; d < 4; d++) {
            int ni = cur_i + di[d];
            int nj = cur_j + dj[d];
            
            // Проверяем, что не вышли за границы
            if (ni >= 0 && ni < N && nj >= 0 && nj < M) {
                // Если это не стена
                if (lab[ni][nj] != '1') {
                    int new_pdf = max_pdf[cur_i][cur_j];
                    
                    // Если на новой клетке лежит файл - прибавляем
                    if (lab[ni][nj] == 'P') {
                        new_pdf = new_pdf + 1;
                    }
                    
                    // Если мы нашли путь с бОльшим количеством файлов, чем было раньше
                    if (new_pdf > max_pdf[ni][nj]) {
                        max_pdf[ni][nj] = new_pdf;
                        
                        // Кидаем клетку в очередь, чтобы пойти из неё дальше
                        q_i[tail] = ni;
                        q_j[tail] = nj;
                        tail = tail + 1;
                    }
                }
            }
        }
    }
    
    cout << "Максимальное количество собранных pdf-файлов: " << max_pdf[end_i][end_j] << endl;
    
    return 0;
}